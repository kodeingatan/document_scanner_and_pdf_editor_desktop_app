const dictionaries: Record<AppLanguage, Dict> = { id, en };

interface I18nState {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  language: 'id',
  setLanguage: (language) => set({ language }),
}));

export function useT(): (key: string, fallback?: string) => string {
  const language = useI18nStore((state) => state.language);
  return (key, fallback) => dictionaries[language][key] ?? fallback ?? key;
}

export function translate(language: AppLanguage, key: string, fallback?: string): string {
  return dictionaries[language][key] ?? fallback ?? key;
}
